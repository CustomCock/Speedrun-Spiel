/** Liefert die Höhe an Gitterposition (gx, gy) – außerhalb = 0 */
export function emblemHeight(name: string, gx: number, gy: number): number {
  const rows = EMBLEMS[name] ?? EMBLEMS.numeral;
  if (gy < 0 || gy >= rows.length) return 0;
  const ch = rows[gy][gx];
  switch (ch) {
    case '1':
      return 0.55;
    case '2':
      return 1;
    case '-':
      return -0.6;
    default:
      return 0;
  }
}
